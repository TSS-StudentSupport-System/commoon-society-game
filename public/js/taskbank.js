// Question banks for personal tasks (ภารกิจส่วนตัว). Short, lower-secondary level, 2 questions per task.
const rnd = (n) => Math.floor(Math.random() * n);
const pickN = (a, n) => { const c = a.slice(); for (let i = c.length - 1; i > 0; i--) { const j = rnd(i + 1); [c[i], c[j]] = [c[j], c[i]]; } return c.slice(0, n); };
const mcq = (q, right, wrongs) => { const options = pickN([right, ...wrongs], wrongs.length + 1); return { q, options, answer: options.indexOf(right) }; };

// ── คณิตศาสตร์: generated so they never repeat ──
function mathQ() {
  const kind = rnd(5);
  const near = (v) => pickN([v + 1, v - 1, v + 2, v - 2, v + 10, v - 10].filter((x) => x !== v && x >= 0), 2).map(String);
  if (kind === 0) { const a = 6 + rnd(7), b = 6 + rnd(7); return mcq(`${a} × ${b} = ?`, String(a * b), near(a * b)); }
  if (kind === 1) { const x = 3 + rnd(15), a = 2 + rnd(20); return mcq(`ถ้า x + ${a} = ${x + a} แล้ว x = ?`, String(x), near(x)); }
  if (kind === 2) { const p = [10, 20, 25, 50][rnd(4)], base = [40, 60, 80, 120, 200][rnd(5)], v = (p * base) / 100; return mcq(`${p}% ของ ${base} เท่ากับเท่าไร`, String(v), near(v)); }
  if (kind === 3) { const d = [2, 3, 4, 5][rnd(4)], m = 2 + rnd(8), whole = d * m, k = 1 + rnd(d - 1); return mcq(`${k}/${d} ของ ${whole} เท่ากับเท่าไร`, String(k * m), near(k * m)); }
  const a = 2 + rnd(6), b = 3 + rnd(6); return mcq(`(${a} + ${b}) × 2 = ?`, String((a + b) * 2), near((a + b) * 2));
}

// ── ภาษาอังกฤษ: friendship and school words ──
const EN = [
  ['kind', 'ใจดี'], ['respect', 'เคารพ'], ['friend', 'เพื่อน'], ['help', 'ช่วยเหลือ'], ['brave', 'กล้าหาญ'],
  ['share', 'แบ่งปัน'], ['honest', 'ซื่อสัตย์'], ['listen', 'ฟัง'], ['apologize', 'ขอโทษ'], ['safe', 'ปลอดภัย'],
  ['trust', 'ไว้วางใจ'], ['homework', 'การบ้าน'], ['classmate', 'เพื่อนร่วมชั้น'], ['include', 'ชวนเข้าร่วมด้วย'], ['tease', 'ล้อเลียน'],
];
function englishQ() {
  const [w, th] = EN[rnd(EN.length)];
  const wrongs = pickN(EN.filter((x) => x[0] !== w), 2);
  return rnd(2)
    ? mcq(`คำว่า "${w}" แปลว่าอะไร`, th, wrongs.map((x) => x[1]))
    : mcq(`"${th}" ภาษาอังกฤษคือคำใด`, w, wrongs.map((x) => x[0]));
}


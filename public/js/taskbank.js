const MAKERS = { math: mathQ, english: englishQ, thai: thaiQ, science: scienceQ, bully: bullyQ, kind: kindQ };
/** two questions for a quiz task; both must be right */
export function makeQuiz(type) {
  const make = MAKERS[type] || bullyQ, out = [];
  for (let i = 0; i < 20 && out.length < 2; i++) { const q = make(); const k = (x) => x.q + [...x.options].sort().join('|'); if (!out.some((x) => k(x) === k(q))) out.push(q); }
  return out;
}
